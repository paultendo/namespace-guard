#!/usr/bin/env node
// generate-latin-fold.js: src/latin-fold.ts, the letters canonicalise() folds to the ASCII letter they're built on,
// beyond the confusable maps: Latin letters with a stroke, hook, bar or accent (ŧ, ɦ, ꞡ, ɏ, İ), dotless i and j,
// small capitals, and modifier and subscript letters.
//
// It also lists the Latin letters not in modern use, from Unicode's Identifier_Type: Recommended (or Inclusion) letters
// such as Sámi ŧ, Turkish İ or German ö appear in ordinary text, so canonicalise() folds them only in a word that shows
// another sign of tampering, or when told the text is Latin (strategy "all"). Technical, obsolete and uncommon letters
// such as ɦ, ꞡ or ꝱ don't, so their presence is that sign.
//
// Letters NFKC already maps to one ASCII letter (fullwidth, mathematical, most modifier letters) aren't listed:
// canonicalise() applies NFKC to them at run time.
//
// Usage: node scripts/generate-latin-fold.js [--ucd <dir with UnicodeData.txt, Scripts.txt, IdentifierType.txt>]
//        (default: ../confusable-vision/data/input)

const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..");
const args = process.argv.slice(2);
const ucd = args.includes("--ucd") ? args[args.indexOf("--ucd") + 1] : path.join(root, "../confusable-vision/data/input");
const read = (f) => fs.readFileSync(path.join(ucd, f), "utf8");

function ranges(text) {
  const out = [];
  for (const line of text.split("\n")) {
    const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([^#]+?)\s*(?:#|$)/);
    if (m) out.push([parseInt(m[1], 16), parseInt(m[2] ?? m[1], 16), m[3]]);
  }
  return out;
}
const lookup = (table, cp) => { for (const [a, b, v] of table) if (cp >= a && cp <= b) return v; return null; };

const scripts = ranges(read("Scripts.txt"));
const idType = ranges(read("IdentifierType.txt"));
const version = (read("Scripts.txt").match(/Scripts-([\d.]+)\.txt/) ?? [])[1] ?? "unknown";
const idVersion = (read("IdentifierType.txt").match(/Version: ([\d.]+)/) ?? [])[1] ?? "unknown";

const ASCII_LETTER = /^[A-Za-z]$/;
// Name shapes that are a letter plus a mark, not a different letter (TURNED A, OPEN O and SCHWA stay out)
const NAMED = [
  [/^LATIN (SMALL|CAPITAL) LETTER ([A-Z]) WITH .+$/, 1, 2],
  [/^LATIN (SMALL|CAPITAL) LETTER (?:BARRED|DOTLESS) ([A-Z])(?: WITH .+)?$/, 1, 2],
  [/^LATIN LETTER SMALL CAPITAL ([A-Z])(?: WITH .+)?$/, null, 1],
  [/^LATIN SUBSCRIPT SMALL LETTER ([A-Z])$/, null, 1],
  [/^MODIFIER LETTER (SMALL|CAPITAL) ([A-Z])(?: WITH .+)?$/, 1, 2],
];

const fold = {};
const notInUse = [];
// A letter IdentifierType.txt doesn't list is Not_Character (its @missing default), so not in modern use
const inModernUse = (cp) => { const t = lookup(idType, cp); return !!t && /\b(Recommended|Inclusion)\b/.test(t); };
for (const line of read("UnicodeData.txt").split("\n")) {
  const [hex, name, gc] = line.split(";");
  if (!hex || !gc?.startsWith("L")) continue;
  const cp = parseInt(hex, 16);
  if (cp < 0x80) continue;
  const ch = String.fromCodePoint(cp);
  const script = lookup(scripts, cp);
  if (script !== "Latin") continue;
  if (!inModernUse(cp)) notInUse.push(ch);
  const nfkc = ch.normalize("NFKC");
  if (ASCII_LETTER.test(nfkc)) continue; // folded at run time
  let base = ch.normalize("NFKD").replace(/\p{M}/gu, "");
  if (!ASCII_LETTER.test(base)) {
    base = null;
    for (const [re, caseGroup, letterGroup] of NAMED) {
      const m = name.match(re);
      if (!m) continue;
      const letter = m[letterGroup];
      // Small capitals and subscripts stand in for lowercase letters
      base = caseGroup && m[caseGroup] === "CAPITAL" ? letter : letter.toLowerCase();
      break;
    }
  }
  if (!base) continue;
  fold[ch] = base;
}

const entries = Object.entries(fold).sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0));
const body = entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const out = `// Generated by scripts/generate-latin-fold.js from the Unicode Character Database ${version} (UnicodeData.txt,
// Scripts.txt) and IdentifierType.txt ${idVersion}, under the Unicode License v3 (https://www.unicode.org/license.txt).
// Do not edit.

/**
 * Latin letters built on an ASCII letter, mapped to it: a letter with a stroke, hook, bar or accent (ŧ, ɦ, ꞡ, ɏ, İ,
 * ö), dotless i and j, small capitals, subscript and modifier letters. Letters NFKC maps to one ASCII letter aren't
 * listed; canonicalise() applies NFKC to those.
 */
export const LATIN_FOLD: Readonly<Record<string, string>> = {
${body}
};

/**
 * Latin letters not in modern use (Unicode Identifier_Type other than Recommended or Inclusion: technical, obsolete,
 * uncommon), such as ɦ, ꞡ, ꝱ or ꟾ. One in a word is a sign the word was tampered with; letters in modern use (ŧ, İ,
 * ö) aren't, so canonicalise() folds those only in a word that shows another sign, or with strategy "all".
 */
export const LATIN_NOT_IN_MODERN_USE: ReadonlySet<string> = new Set(${JSON.stringify(notInUse.join(""))});
`;
fs.writeFileSync(path.join(root, "src/latin-fold.ts"), out);
console.log(`src/latin-fold.ts: ${entries.length} letters to fold, ${notInUse.length} Latin letters not in modern use (UCD ${version}, IdentifierType ${idVersion})`);
for (const c of ["ŧ", "ɦ", "ꞡ", "ɏ", "İ", "ö", "ɐ", "ǝ", "ı", "ʙ", "ꝱ", "ƙ", "ᶈ", "ᵴ", "ꟾ", "ᵂ", "ł", "đ"])
  console.log(`  ${c} U+${c.codePointAt(0).toString(16).toUpperCase().padStart(4, "0")} -> ${fold[c] ?? "(none)"}${notInUse.includes(c) ? "  not in modern use" : ""}`);
